// Async loader function to fetch the complete 3,000+ Unicode emoji dataset
export async function loadMassiveUnicodeEmojiDataset(): Promise<EmojiCategory[]> {
  try {
    const res = await fetch('https://cdn.jsdelivr.net/npm/unicode-emoji-json@0.6.0/data-by-group.json');
    if (!res.ok) throw new Error('Failed to fetch OpenEmoji/Unicode JSON');
    const rawData = await res.json();

    // Map fetched groups into our 8 structured categories
    const categories: EmojiCategory[] = CATEGORY_DEFINITIONS.map((def) => ({
      id: def.id,
      name: def.name,
      icon: def.icon,
      emojis: [],
    }));

    Object.keys(rawData).forEach((groupName) => {
      const itemsInGroup = rawData[groupName] || [];
      const lowerGroupName = groupName.toLowerCase();

      // Find best matching category
      let targetCat = categories.find((c) => {
        const def = CATEGORY_DEFINITIONS.find((d) => d.id === c.id);
        return def?.matchGroups.some((mg) => mg.toLowerCase() === lowerGroupName || lowerGroupName.includes(mg.toLowerCase()));
      });

      if (!targetCat) {
        if (lowerGroupName.includes('people') || lowerGroupName.includes('person') || lowerGroupName.includes('component')) {
          targetCat = categories.find((c) => c.id === 'people');
        } else if (lowerGroupName.includes('animal') || lowerGroupName.includes('nature') || lowerGroupName.includes('plant')) {
          targetCat = categories.find((c) => c.id === 'animals');
        } else if (lowerGroupName.includes('food') || lowerGroupName.includes('drink')) {
          targetCat = categories.find((c) => c.id === 'food');
        } else if (lowerGroupName.includes('activity') || lowerGroupName.includes('sport')) {
          targetCat = categories.find((c) => c.id === 'activity');
        } else if (lowerGroupName.includes('travel') || lowerGroupName.includes('place')) {
          targetCat = categories.find((c) => c.id === 'travel');
        } else if (lowerGroupName.includes('object') || lowerGroupName.includes('tool') || lowerGroupName.includes('tech')) {
          targetCat = categories.find((c) => c.id === 'objects');
        } else if (lowerGroupName.includes('symbol') || lowerGroupName.includes('flag')) {
          targetCat = categories.find((c) => c.id === 'symbols');
        } else {
          targetCat = categories.find((c) => c.id === 'smileys');
        }
      }

      if (targetCat) {
        itemsInGroup.forEach((item: any) => {
          if (item && item.emoji && item.name) {
            targetCat!.emojis.push({
              char: item.emoji,
              name: item.name,
              category: targetCat!.name,
              keywords: item.keywords || [item.name],
            });
          }
        });
      }
    });

    // Verify all categories have emojis, if not fall back to default for empty ones
    categories.forEach((cat) => {
      if (cat.emojis.length === 0) {
        const def = DEFAULT_EMOJI_CATEGORIES.find((d) => d.id === cat.id);
        if (def) cat.emojis = def.emojis;
      }
    });

    return categories;
  } catch (err) {
    console.warn('Network fetch for 3,000+ emojis failed, using built-in high density set', err);
    return DEFAULT_EMOJI_CATEGORIES;
  }
}
